alter table public.operators
  add column if not exists invitation_status text not null default 'invited'
    check (invitation_status in ('invited', 'active', 'disabled')),
  add column if not exists invited_at timestamptz,
  add column if not exists activated_at timestamptz,
  add column if not exists disabled_at timestamptz;

update public.operators
set invited_at = coalesce(invited_at, created_at, now())
where invited_at is null;

create index if not exists operators_invitation_status_idx
  on public.operators (invitation_status);

create table if not exists public.operator_funnel_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in (
    'landing_view',
    'getting_started_cta_clicked',
    'otp_requested',
    'otp_verified',
    'getting_started_step_1_viewed',
    'getting_started_step_1_completed'
  )),
  visitor_id text not null,
  email text,
  path text,
  created_at timestamptz not null default now()
);

create index if not exists operator_funnel_events_created_at_idx
  on public.operator_funnel_events (created_at desc);

create index if not exists operator_funnel_events_name_created_at_idx
  on public.operator_funnel_events (event_name, created_at desc);

alter table public.operator_funnel_events enable row level security;
